def extlang(path):
    ext=Path(path).suffix.lower().lstrip(".")
    for lang,exts in LANG.items():
        if ext in exts:return lang
    return "unknown"

def tree(files):
    lines=[]
    for name in sorted(files):
        parts=Path(name).parts
        lines.append("  "*max(0,len(parts)-1)+"└─ "+parts[-1]+" ["+extlang(name)+"]")
    return "\n".join(lines)

