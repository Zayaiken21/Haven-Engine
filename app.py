@app.post("/chat")
def chat(c:Chat):
    remember("user",c.message)
    q=c.message.lower()
    if "github" in q: reply=KNOWLEDGE["github"]
    elif "render" in q or "persistent" in q: reply=KNOWLEDGE["render"]
    elif "storage" in q or "memory" in q: reply=KNOWLEDGE["storage"]
    elif "accurate" in q or "100%" in q: reply=KNOWLEDGE["accuracy"]
    elif "bad message" in q or "download" in q: reply=KNOWLEDGE["bad message"]
    elif "file" in q or "folder" in q: reply="I can inspect the supplied project file names, classify them by language, and build a deterministic project tree. Current files: "+(", ".join(c.files) if c.files else "none.")
    else: reply="The Haven Engine received your question. I am a deterministic rules-and-knowledge engine, not a generative AI. I can explain supported engineering concepts, inspect project structure, and run the build pipeline. For new capabilities, add a rule/template/validator to the engine."
    remember("assistant",reply)
    return {"reply":reply}

@app.post("/projects/build")
def build(b:Build):
    pid=str(uuid.uuid4()); p=PROJECTS/pid;p.mkdir()
    generated=generate(b.kind,b.request)
    # User files are copied into a safe source directory; generated files win only on exact collision.
    for n,v in b.files.items():
        n=n.replace("\\","/")
        if ".." in Path(n).parts or n.startswith("/"): continue
        if n not in generated: generated[n]=v if isinstance(v,str) else str(v)
    manifest={"project_id":pid,"name":b.name,"request":b.request,"created_at":now(),"files":sorted(generated),"tree":tree(generated)}
    (p/"manifest.json").write_text(json.dumps(manifest,indent=2),encoding="utf8")
    (p/"files.json").write_text(json.dumps(generated,indent=2,ensure_ascii=False),encoding="utf8")
    return {"project_id":pid,"files":generated,"manifest":manifest}

@app.get("/projects/{pid}/download")
def download(pid:str):
    p=PROJECTS/pid
    if not p.exists(): raise HTTPException(404,"Project not found")
    data=json.loads((p/"files.json").read_text(encoding="utf8"))
    z=p/"The-Haven-Project.zip"
    with zipfile.ZipFile(z,"w",zipfile.ZIP_DEFLATED) as out:
        for n,v in data.items(): out.writestr(n,v)
        out.writestr("HAVEN-MANIFEST.json",(p/"manifest.json").read_text(encoding="utf8"))
    return FileResponse(z,media_type="application/zip",filename="The-Haven-Project.zip")

@app.post("/uploads")
async def uploads(files:list[UploadFile]=File(...)):
    saved=[]
    for f in files:
        uid=str(uuid.uuid4()); safe=Path(f.filename or "upload.bin").name
        dest=UPLOADS/(uid+"-"+safe)
        with dest.open("wb") as out: shutil.copyfileobj(f.file,out)
        saved.append({"id":uid,"name":safe,"size":dest.stat().st_size})
    return {"saved":saved}
